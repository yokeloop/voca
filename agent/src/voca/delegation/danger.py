def level(description: str | None) -> Danger:
    if not description:
        return Danger.HIGH
    found = RULES.get(description)
    if found is not None:
        return found
    found = RULES.get(re.sub(r"\s*\(.*\)\s*$", "", description))
    if found is not None:
        return found
    return Danger.HIGH
